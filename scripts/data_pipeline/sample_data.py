"""Step 2 - Representative reduction (stratified, seed 42, never df.head()).

If the extract is within MAX_ROWS the full population is retained (no reduction, no information loss).
Otherwise: stratified sampling with >=1 record per stratum (rare strata always survive) and the
remaining budget allocated proportionally (largest-remainder). Stratum = source x facility x team x
status x month. Writes data/quality/sampling_report.md with coverage checks.
"""
import numpy as np
import pandas as pd
from _common import *

STRATA = ["source_system", "facility", "team", "status_label", "period"]
COVERAGE = ["source_system", "facility", "team", "status_label", "record_date"]


def prep(df):
    df = df.copy()
    df["status_label"] = df["node_status"].where(df["node_status"] != "", df["coverage_status"])
    df["period"] = df["record_date"].str.slice(0, 7)
    return df


def reduce(df, max_rows=MAX_ROWS, seed=RANDOM_SEED):
    if len(df) <= max_rows:
        return df.copy(), "full_population_retained"
    key = df[STRATA].astype(str).agg("|".join, axis=1)
    size = key.value_counts().sort_index()
    alloc = pd.Series(1, index=size.index)
    spare = max_rows - len(size)
    if spare < 0:
        raise SystemExit("More strata than allowed rows; coarsen STRATA")
    room = size - 1
    share = room / room.sum() * spare if room.sum() else room * 0
    alloc += np.minimum(np.floor(share).astype(int), room)
    left = max_rows - int(alloc.sum())
    frac = (share - np.floor(share)).where(alloc < size, -1).sort_values(ascending=False, kind="stable")
    for k in frac.index[:max(left, 0)]:
        if alloc[k] < size[k]:
            alloc[k] += 1
    parts = [df[key == k].sample(n=int(alloc[k]), random_state=seed) for k in size.index]
    return pd.concat(parts).sort_index(), "stratified_sample"


def coverage_rows(before, after):
    out = []
    for c in COVERAGE:
        b, a = set(before[c].astype(str)), set(after[c].astype(str))
        out.append((c, len(b), len(a), ", ".join(sorted(b - a)) or "none"))
    return out


def main():
    raw = pd.read_csv(SOURCE_SAMPLE, dtype=str, keep_default_na=False)
    stats = load_stats()
    before = prep(raw)
    after, method = reduce(before)
    after = after.reset_index(drop=True)
    after[SOURCE_COLUMNS].to_csv(SOURCE_SAMPLE, index=False, encoding="utf-8", lineterminator="\n")
    cov = coverage_rows(before, after)
    rare = before[before["status_label"].isin(["Critical"])]
    rare_kept = after[after["status_label"].isin(["Critical"])]
    lines = [
        "# Sampling Report (generated by scripts/data_pipeline/sample_data.py)", "",
        f"- Method: `{method}`", f"- Random seed: {RANDOM_SEED} (used only if reduction is needed)",
        f"- Row limit: {MAX_ROWS:,} rows / {MAX_COLS} columns",
        f"- Original extract: {len(before)} rows x {stats.get('original_column_count', len(SOURCE_COLUMNS))} columns",
        f"- Final source sample: {len(after)} rows x {len(SOURCE_COLUMNS)} columns",
        f"- Rows removed: {len(before) - len(after)}", "",
        "## Coverage checks (distinct values before vs after)", "",
        "| Field | Before | After | Missing after sampling |", "|---|---:|---:|---|",
        *[f"| {c} | {b} | {a} | {m} |" for c, b, a, m in cov], "",
        "## Rare-record preservation", "",
        f"- Critical-status rows (rarest class, ~10% of backend rows by design): {len(rare)} before, {len(rare_kept)} after.",
        "- Every facility x team x status x month stratum keeps at least one record.", "",
        "## Notes", "",
        "- The extract is far below the row limit, so no records were dropped; df.head() is never used.",
        "- UI-only interpolated Last-30-Days / Year-to-Date series are excluded (derived, not source data).",
    ]
    SAMPLING_REPORT.write_text("\n".join(lines) + "\n", "utf-8")
    save_stats({"sampling_method": method, "sample_record_count": len(after),
                "sample_column_count": len(SOURCE_COLUMNS), "rows_removed": len(before) - len(after)})
    print(f"{method}: {len(before)} -> {len(after)} rows")


if __name__ == "__main__":
    main()
