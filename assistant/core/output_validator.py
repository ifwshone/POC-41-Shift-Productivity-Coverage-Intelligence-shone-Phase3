import re
import json

def validate_numeric_fidelity(text: str, result_data: dict) -> bool:
    """
    Validates that all numbers generated by the LLM exist within the 
    approved deterministic evidence package.
    Resolves Phase 3 Finding B1: Removes blanket whitelists and strictly 
    binds LLM outputs to the provided context.
    """
    if not text:
        return False
        
    # 1. Extract all numbers (integers and decimals) from the LLM's text
    llm_numbers = set(re.findall(r'\b\d+(?:\.\d+)?\b', text))
    
    # 2. Extract all allowed numbers directly from the deterministic payload
    # By dumping the payload to a string, we capture ranks, values, and dates automatically
    result_str = json.dumps(result_data)
    allowed_numbers = set(re.findall(r'\b\d+(?:\.\d+)?\b', result_str))
    
    # 3. Check for hallucinations
    # If the LLM generated any number that isn't in the allowed payload, reject it.
    hallucinated_numbers = llm_numbers - allowed_numbers
    
    if hallucinated_numbers:
        # Fails the validation, forcing the system to fall back to the deterministic answer
        return False
        
    return True
    return True