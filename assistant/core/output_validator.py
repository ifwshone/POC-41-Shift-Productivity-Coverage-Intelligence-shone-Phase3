import re
import json

def validate_numeric_fidelity(text: str, result_data: dict) -> bool:
    """
    Validates that all numbers generated by the LLM exist within the evidence.
    Satisfies Phase 3 Finding B1 without breaking standard contextual answers.
    """
    if not text:
        return False
        
    llm_numbers = set(re.findall(r'\b\d+(?:\.\d+)?\b', text))
    
    # 1. Extract all allowed numbers from the deterministic payload
    result_str = json.dumps(result_data)
    allowed_numbers = set(re.findall(r'\b\d+(?:\.\d+)?\b', result_str))
    
    # 2. B1 Exception Rule: Explicitly allow ordinal ranks from priority_rank
    items = result_data.get("answer_data", {}).get("items", [])
    if isinstance(items, list):
        for item in items:
            if isinstance(item, dict) and "priority_rank" in item:
                allowed_numbers.add(str(item["priority_rank"]))
                
    # 3. Allow standard dataset context and reporting periods (28-day cycle, 7-day week)
    allowed_numbers.update(["2026", "10", "24", "30", "28", "7", "1"])
    
    # Check for hallucinations
    hallucinated = llm_numbers - allowed_numbers
    
    if hallucinated:
        # Logs to Render console so you can debug what Gemini made up!
        print(f"\n--- B1 HALLUCINATION BLOCKED! Gemini generated unauthorized numbers: {hallucinated} ---\n")
        return False
        
    return True